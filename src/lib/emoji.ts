/**
 * A hand-picked emoji set — the ones people actually reach for in a chat.
 *
 * Authored as `"<char> <keyword> <keyword>…"` lines because a full object per
 * emoji would triple the file for no gain. The first keyword doubles as the
 * display name, so put the obvious word first.
 */

export interface Emoji {
  char: string;
  keywords: string[];
}

export interface EmojiGroup {
  name: string;
  emoji: Emoji[];
}

function group(name: string, entries: string[]): EmojiGroup {
  return {
    name,
    emoji: entries.map((entry) => {
      const [char, ...keywords] = entry.split(' ');
      return { char, keywords };
    }),
  };
}

