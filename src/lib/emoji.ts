/** The six one-tap reactions offered on a message. */
export const QUICK_REACTIONS: string[] = ['👍', '❤️', '😂', '😮', '😢', '🙏'];

const ALL_EMOJI: Emoji[] = EMOJI_GROUPS.flatMap((entry) => entry.emoji);

const NAMES = new Map(ALL_EMOJI.map((entry) => [entry.char, entry.keywords[0] ?? '']));

/** The leading keyword, tidied for display — `''` for anything not in the set. */
export function emojiName(char: string): string {
  return (NAMES.get(char) ?? '').replace(/-/g, ' ');
}

/**
 * Keyword search. A keyword that *starts* with the term outranks one that
 * merely contains it, so "car" leads with 🚗 rather than 🃏.
 */
export function searchEmoji(term: string, limit = 48): string[] {
  const query = term.trim().toLowerCase();
  if (!query) return [];

  const leading: string[] = [];
  const trailing: string[] = [];

  for (const entry of ALL_EMOJI) {
    if (entry.keywords.some((keyword) => keyword.startsWith(query))) {
      leading.push(entry.char);
      if (leading.length >= limit) break;
    } else if (entry.keywords.some((keyword) => keyword.includes(query))) {
      trailing.push(entry.char);
    }
  }

  return leading.concat(trailing).slice(0, limit);
}
